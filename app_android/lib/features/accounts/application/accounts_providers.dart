@Riverpod(keepAlive: true)
AccountsRepository accountsRepository(Ref ref) => AccountsRepository(
  db: ref.watch(appDatabaseProvider),
  writer: ref.watch(outboxWriterProvider),
  isPremium: () => ref.read(isPremiumProvider.future),
);

// The providers below return Drift row types. Those are generated by drift
// (not visible to riverpod_generator), so they are declared by hand.

/// Live accounts (archived included), in list order.
final allAccountsProvider = StreamProvider.autoDispose<List<AccountRow>>(
  (ref) => ref.watch(accountsRepositoryProvider).watchAll(),
);

final accountByIdProvider = StreamProvider.autoDispose
    .family<AccountRow?, String>(
      (ref, id) => ref.watch(accountsRepositoryProvider).watchOne(id),
    );

/// Transactions of one account (as source or destination), newest first.
final accountTransactionsProvider = StreamProvider.autoDispose
    .family<List<TransactionRow>, String>(
      (ref, accountId) => ref
          .watch(appDatabaseProvider)
          .transactionsDao
          .watchFiltered(limit: 30, accountId: accountId),
    );

/// Balance snapshots of one account, newest first.
final accountSnapshotsProvider = StreamProvider.autoDispose
    .family<List<BalanceSnapshotRow>, String>(
      (ref, accountId) => ref
          .watch(appDatabaseProvider)
          .balanceSnapshotsDao
          .watchByAccount(accountId),
    );

/// Every live transaction; the balance formulas need the full history.
final allTransactionsProvider =
    StreamProvider.autoDispose<List<TransactionRow>>(
      (ref) => ref.watch(appDatabaseProvider).transactionsDao.watchAllActive(),
    );

/// Accounts with their expected balance today (BUSINESS_RULES §4.2), computed
/// by `core/domain_rules` — never by a screen.
@riverpod
Future<List<AccountWithBalance>> accountBalances(Ref ref) async {
  final accounts = await ref.watch(allAccountsProvider.future);
  final live = await ref.watch(allTransactionsProvider.future);
  final txs = [for (final row in live) row.toDomain()];
  final today = todayCivil();
  return [
    for (final account in accounts)
      AccountWithBalance(
        account: account,
        expectedBalance: expectedBalance(account.toDomain(), txs, today),
      ),
  ];
}

/// Balances plus the expected total, both from `core/domain_rules`.
@riverpod
Future<AccountsOverview> accountsOverview(Ref ref) async {
  final items = await ref.watch(accountBalancesProvider.future);
  final live = await ref.watch(allTransactionsProvider.future);
  final total = expectedTotal(
    [for (final item in items) item.account.toDomain()],
    [for (final row in live) row.toDomain()],
    todayCivil(),
  );
  return AccountsOverview(items: items, expectedTotal: total);
}
